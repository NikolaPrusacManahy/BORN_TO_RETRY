// Update 0.0.13 — the nine fight rooms at twice the size (the designer: rooms twice as big, more walls to use and room
// to fight in). Each is drawn as its top-left quarter (rooms.ts's legend) and mirrored right and down, so its middle
// lines up with the doors. The quarter's last column (rows 0–1) and last row (columns 0–1) stay clear: the doorways.
// More long inner walls than before, to wall-run along and hide behind; pads to launch from for a ground slam.
import type { RoomTemplate } from './rooms';

/** A room from its top-left quarter, mirrored right and down. */
export function quarter(rows: string[]): string[] {
  const half = rows.map((r) => r + [...r].reverse().join(''));
  return [...half, ...[...half].reverse()];
}

const room = (id: string, rows: string[]): RoomTemplate => ({ id, kind: 'fight', rows: quarter(rows) });

