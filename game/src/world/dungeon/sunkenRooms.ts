// Update 0.2.11 — floor 6's own rooms, the Sunken Grove (the designer: "a floor that has been fully flooded … moss,
// rotten surface, trees"; the rooms are Claude's). Ten, each with its own idea. Under water you swim (sim/player/swim.ts),
// so every room is fought in three dimensions: ledges and towers are reached from any side, and height is for cover
// and lines of sight, not for escape. Drowned trees (D) and seaweed (~) grow out of beds of silt, never out of paving;
// low cover is mossy boulders. No pits, no jump pads. Floor cells always join every door. Drawn as quarters like the
// others (fightRooms.ts). From floor 6 on. And its own challenge room (the designer: "Yes, design one"), the drowned
// heart: never on the way, always the floor's challenge room.
